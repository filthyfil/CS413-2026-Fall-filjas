"""Language-tool adapter: the only code that talks to lambda1.py.

Every operation returns a result dict (see ARCHITECTURE.md, "Backend
contract"):

    {"op": str, "revision": int, "status": STATUS, "message": str,
     "errorKind": ERROR_KIND | None, "value": str | None, "details": dict}

STATUS is "ok", "error" (problem with the user's program), "failure" (the
tools themselves broke), "not_implemented" or "cancelled". ERROR_KIND is
"input", "language", "runtime" or "backend".
"""
from . import lambda1 as L
from .reader import ReadError, read_d0exp
from .runner import InterpretRunner


def make_result(op: str, revision: int, status: str, message: str, *,
                error_kind: str | None = None, value: str | None = None,
                details: dict | None = None) -> dict:
    return {"op": op, "revision": revision, "status": status,
            "message": message, "errorKind": error_kind, "value": value,
            "details": details or {}}


def free_variables(dexp: L.D0E000) -> frozenset[str]:
    """Free variable names of dexp (delegates to lambda1.d0exp_fvset)."""
    return L.d0exp_fvset(dexp)


def lint_source(source: str) -> tuple[str, str, str | None, dict]:
    """(status, message, error_kind, details) for Lint. Never evaluates."""
    try:
        dexp = read_d0exp(source)
    except ReadError as exc:
        return "error", f"Invalid input: {exc}", "input", {}
    names = sorted(free_variables(dexp))
    if names:
        return ("error", "Undeclared variable(s): " + ", ".join(names),
                "language", {"freeVariables": names})
    return "ok", "No free variables found.", None, {"freeVariables": []}


def contains_error_value(dval) -> bool:
    """True for the D0V000() error sentinel, directly or inside a pair."""
    if type(dval) is L.D0V000:
        return True
    if isinstance(dval, L.D0Vpair):
        return contains_error_value(dval.arg1) or contains_error_value(dval.arg2)
    return False


def evaluate_source(source: str) -> tuple[str, str, str | None, str | None]:
    """(status, message, error_kind, value) for Interpret.

    Runs d0exp_evaluate in the calling process; InterpretRunner calls this
    inside a child process so that a run can be stopped.
    """
    try:
        dexp = read_d0exp(source)
    except ReadError as exc:
        return "error", f"Invalid input: {exc}", "input", None
    try:
        dval = L.d0exp_evaluate(dexp, L.ENVnil())
    except RecursionError:
        return ("error", "Runtime error: recursion too deep (RecursionError)",
                "runtime", None)
    except Exception as exc:  # TypeError, ZeroDivisionError, ...
        return ("error", f"Runtime error: {type(exc).__name__}: {exc}",
                "runtime", None)
    try:
        text = repr(dval)
    except (RecursionError, ValueError) as exc:
        return ("error", f"The value could not be displayed: "
                f"{type(exc).__name__}: {exc}", "runtime", None)
    if contains_error_value(dval):
        return ("error", "Runtime error: evaluation produced the error value "
                "D0V000() (for example, an unbound variable)", "runtime", text)
    return "ok", "Evaluation succeeded.", None, text


TYPECHECK_MESSAGE = "Type checking is not yet implemented."
COMPILE_MESSAGE = "Compilation is not yet implemented."
EXECUTE_UNAVAILABLE = ("Execute runs code generated by Compile. No generated "
                       "artifact is available because compilation is not yet "
                       "implemented.")


class LanguageTools:
    """Backend entry points used by the HTTP layer (server/app.py)."""

    def __init__(self, runner: InterpretRunner | None = None):
        self.runner = runner or InterpretRunner()

    def lint(self, source: str, revision: int) -> dict:
        status, message, kind, details = lint_source(source)
        return make_result("lint", revision, status, message,
                           error_kind=kind, details=details)

    def interpret(self, source: str, revision: int, run_id: str) -> dict:
        outcome = self.runner.run(source, run_id)
        if outcome.cancelled:
            return make_result("interpret", revision, "cancelled",
                               "Interpretation was stopped by the user.")
        if outcome.crash is not None:
            return make_result("interpret", revision, "failure",
                               f"Interpreter process failed: {outcome.crash}",
                               error_kind="backend")
        status, message, kind, value = outcome.result
        return make_result("interpret", revision, status, message,
                           error_kind=kind, value=value)

    def cancel(self, run_id: str) -> bool:
        return self.runner.cancel(run_id)

    def typecheck(self, source: str, revision: int) -> dict:
        return make_result("typecheck", revision, "not_implemented",
                           TYPECHECK_MESSAGE)

    def compile(self, source: str, revision: int) -> dict:
        # A real compiler would return status "ok" with
        # details["artifact"] = {"revision", "format", "code"}.
        return make_result("compile", revision, "not_implemented",
                           COMPILE_MESSAGE)

    def execute(self, artifact: dict | None, revision: int) -> dict:
        if not artifact:
            return make_result("execute", revision, "error",
                               EXECUTE_UNAVAILABLE, error_kind="input")
        if artifact.get("revision") != revision:
            return make_result("execute", revision, "error",
                               "The artifact belongs to a different source "
                               "revision; compile again.", error_kind="input")
        return make_result("execute", revision, "not_implemented",
                           "Executing generated code is not yet implemented.")

    def shutdown(self) -> None:
        self.runner.shutdown()
