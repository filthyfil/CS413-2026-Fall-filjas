// Model: application state and the rules that govern it.
//
// No DOM, no fetch, no HTTP. The Controller is the only code that calls
// the mutating methods; the View subscribes and re-renders on change.

export const MAX_SOURCE_BYTES = 1_000_000;   // mirrored in server/reader.py
export const SOURCE_OPS = ["lint", "interpret", "typecheck", "compile"];
export const OPERATIONS = [...SOURCE_OPS, "execute"];

const utf8 = new TextEncoder();

export function optionsProblem({ kind, execBudget, obsBudget }) {
  if (typeof kind !== "string" || kind.trim() === "") {
    return "Enter a result kind: nat, bool, or a pair such as (nat, bool).";
  }
  for (const [label, budget] of [["Execution", execBudget], ["Observation", obsBudget]]) {
    if (!Number.isInteger(budget) || budget < 0 || budget > MAX_BUDGET) {
      return `${label} budget must be a whole number from 0 to ${MAX_BUDGET}.`;
    }
  }
  return null;
}

export function sourceProblem(text) {
  if (typeof text !== "string" || text.trim() === "") {
    return "The source is empty. Enter a program.";
  }
  const bytes = utf8.encode(text).length;
  if (bytes > MAX_SOURCE_BYTES) {
    return `The source is ${bytes} bytes; the limit is ${MAX_SOURCE_BYTES} bytes.`;
  }
  return null;
}

export const DEFAULT_OPTIONS = Object.freeze({
  kind: "nat", execBudget: 100000, obsBudget: 100000,
});
export const MAX_BUDGET = 5000000;   // mirrored in server/tools.py

const OK = Object.freeze({ ok: true });
const no = (reason) => ({ ok: false, reason });

export class AppModel {
  #listeners = new Set();

  constructor() {
    this.revision = 0;      // last revision number handed out
    this.applied = null;    // {name, text, revision}: what tools operate on
    this.draft = null;      // {name, text, base, fromApplied}: editor content
    this.busy = null;       // {op, runId, revision, stopping}
    this.results = [];      // newest first, all for applied.revision
    this.artifact = null;   // generated code {revision, format, code}
    this.notice = null;     // {kind: "error" | "info", text}
    this.retryOp = null;    // operation to offer for retry after a failure
    this.options = { ...DEFAULT_OPTIONS };   // Execute: result kind, budgets
  }

  // ---- observation -----------------------------------------------------

  subscribe(listener) {
    this.#listeners.add(listener);
    return () => this.#listeners.delete(listener);
  }

  #changed() {
    for (const listener of this.#listeners) listener(this);
  }

  // ---- derived state ---------------------------------------------------

  get hasUnappliedEdits() {
    return this.draft !== null && this.draft.text !== this.draft.base;
  }

  // True when the editor shows exactly the applied source.
  get inSync() {
    return this.applied !== null && this.draft !== null &&
      this.draft.fromApplied && !this.hasUnappliedEdits;
  }

  get canEdit() {
    return this.busy === null && this.draft !== null;
  }

  get canReplaceSource() {
    return this.busy === null && !this.hasUnappliedEdits;
  }

  get canApply() {
    return this.busy === null && this.draft !== null &&
      (this.hasUnappliedEdits || !this.draft.fromApplied);
  }

  // Discard returns the editor to the applied source (or to blank).
  get canDiscard() {
    return this.busy === null && this.draft !== null &&
      (this.hasUnappliedEdits || (this.applied !== null && !this.draft.fromApplied));
  }

  get canClearResults() {
    return this.results.length > 0;
  }

  get hasCurrentArtifact() {
    return this.artifact !== null && this.applied !== null &&
      this.artifact.revision === this.applied.revision;
  }

  // Why `op` cannot run now, or null if it can.
  blockedReason(op) {
    if (!OPERATIONS.includes(op)) return `Unknown operation: ${op}.`;
    if (this.busy) return `Busy: ${this.busy.op} is running.`;
    if (op === "execute" && !this.hasCurrentArtifact) {
      return "Execute runs code generated by Compile. Compile this revision first.";
    }
    if (op === "execute") {
      const problem = optionsProblem(this.options);
      if (problem) return problem;
    }
    if (this.applied === null) return "Load or enter a program and apply it first.";
    if (!this.inSync) {
      return this.draft.fromApplied ? "Apply or discard your changes first."
        : "The editor holds a new program: apply it (or discard it) first.";
    }
    return null;
  }

  canRun(op) {
    return this.blockedReason(op) === null;
  }

  // ---- source changes --------------------------------------------------

  // Replace the source with an upload or a canned example.
  loadSource(name, text) {
    if (!this.canReplaceSource) return this.#refuse(this.#replaceBlocked());
    const problem = sourceProblem(text);
    if (problem) return this.rejectSource(`${name} was not loaded: ${problem}`);
    this.#newRevision(name, text);
    return OK;
  }

  // Open a blank editor for typing a program.
  openManualInput() {
    if (!this.canReplaceSource) return this.#refuse(this.#replaceBlocked());
    this.draft = { name: "Manual input", text: "", base: "", fromApplied: false };
    this.notice = null;
    this.#changed();
    return OK;
  }

  editDraft(text) {
    if (!this.canEdit) return no(this.busy ? "Busy." : "No editor is open.");
    if (this.draft.text === text) return OK;
    this.draft = { ...this.draft, text };
    this.#changed();
    return OK;
  }

  applyDraft() {
    if (!this.canApply) return this.#refuse("There are no changes to apply.");
    const problem = sourceProblem(this.draft.text);
    // Rejected edits stay in the draft for correction.
    if (problem) return this.rejectSource(`Changes not applied: ${problem}`);
    this.#newRevision(this.draft.name, this.draft.text);
    return OK;
  }

  discardDraft() {
    if (!this.canDiscard) return this.#refuse("There are no changes to discard.");
    const a = this.applied;
    this.draft = a ? { name: a.name, text: a.text, base: a.text, fromApplied: true }
      : { ...this.draft, text: this.draft.base };
    this.notice = null;
    this.#changed();
    return OK;
  }

  // Record a rejected change; the applied source is left untouched.
  rejectSource(text) {
    this.notice = { kind: "error", text };
    this.#changed();
    return no(text);
  }

  #newRevision(name, text) {
    this.revision += 1;
    this.applied = { name, text, revision: this.revision };
    this.draft = { name, text, base: text, fromApplied: true };
    this.results = [];
    this.artifact = null;
    this.retryOp = null;
    this.notice = { kind: "info", text: `Applied ${name} as revision ${this.revision}.` };
    this.#changed();
  }

  #replaceBlocked() {
    return this.busy ? `Busy: ${this.busy.op} is running.`
      : "Apply or discard your changes before loading another source.";
  }

  #refuse(reason) {
    this.notice = { kind: "error", text: reason };
    this.#changed();
    return no(reason);
  }

  // ---- Execute options -------------------------------------------------

  // Budgets arrive as input text; they are stored as numbers when valid
  // and as the raw text otherwise, so the problem can be reported.
  setOption(name, value) {
    if (!(name in DEFAULT_OPTIONS)) return no(`Unknown option: ${name}.`);
    if (this.busy) return no("Busy.");
    let stored = value;
    if (name !== "kind") {
      const text = String(value).trim();
      stored = /^\d+$/.test(text) ? Number(text) : text;
    }
    if (this.options[name] === stored) return OK;
    this.options = { ...this.options, [name]: stored };
    this.#changed();
    return OK;
  }

  // ---- operations ------------------------------------------------------

  beginOperation(op, runId) {
    const reason = this.blockedReason(op);
    if (reason) return this.#refuse(reason);
    this.busy = { op, runId, revision: this.applied.revision, stopping: false };
    this.notice = null;
    this.retryOp = null;
    this.#changed();
    return OK;
  }

  markStopping() {
    if (!this.busy || this.busy.stopping) return no("Nothing to stop.");
    this.busy = { ...this.busy, stopping: true };
    this.#changed();
    return OK;
  }

  // Remove shown results (and the retry offer that refers to them).
  // Source, revision and artifact are unchanged.
  clearResults() {
    if (!this.canClearResults) return no("There are no results to clear.");
    this.results = [];
    this.retryOp = null;
    this.#changed();
    return OK;
  }

  // Accept a result for the running operation; stale results are ignored.
  completeOperation(result) {
    const busy = this.busy;
    if (!busy || result.op !== busy.op || result.revision !== busy.revision ||
        this.applied?.revision !== result.revision) {
      return no("Stale result ignored.");
    }
    this.busy = null;
    this.results = [result, ...this.results];
    if (result.status === "failure" || result.status === "cancelled") {
      this.retryOp = result.op;
    }
    const artifact = result.details?.artifact;
    if (result.op === "compile" && result.status === "ok" && artifact &&
        artifact.revision === this.applied.revision) {
      this.artifact = artifact;
    }
    this.#changed();
    return OK;
  }
}
